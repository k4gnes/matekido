const RANK = new Map();
for (const [grade, ids] of Object.entries(CURRICULUM_ORDER)) {
    const ranks = new Map();
    ids.forEach((id, index) => ranks.set(id, index));
    RANK.set(Number(grade), ranks);
}

export function curriculumSort(lessonList, grade) {
    const ranks = RANK.get(grade);
    if (!ranks) return lessonList.slice();
    return lessonList.slice().sort((a, b) => {
        const ra = ranks.get(a.id) ?? Number.MAX_SAFE_INTEGER;
        const rb = ranks.get(b.id) ?? Number.MAX_SAFE_INTEGER;
        return ra - rb;
    });
}
